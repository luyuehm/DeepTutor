def upsert_sso_user(
    profile: SsoProfile,
    *,
    role: str = "user",
    preset: str = "standard",
) -> dict[str, Any]:
    """Map a verified SSO profile to a local account, creating it if needed.

    The local username is derived from the stable SSO key so the same IdP
    subject always resolves to the same account: ``sso-<protocol>-<digest>``.
    This keeps SSO logins independent of the local password store — an SSO
    account has no password and cannot be taken over through a local password
    reset.
    """
    from deeptutor.multi_user.identity import save_user
    from deeptutor.services.auth import list_users

    key = profile.key()
    digest = hashlib.sha256(key.encode("utf-8")).hexdigest()[:16]
    username = f"sso-{digest}"

    existing = next((u for u in list_users() if u.get("username") == username), None)
    if existing is not None:
        return existing

    # ``save_user`` with a random bcrypt hash means the account cannot be
    # logged into via the local password path.
    import bcrypt

    placeholder_hash = bcrypt.hashpw(secrets.token_bytes(24), bcrypt.gensalt()).decode()
    record = save_user(
        username,
        placeholder_hash,
        role=role,  # type: ignore[arg-type]
        preset=preset,  # type: ignore[arg-type]
    )
    logger.info("Created SSO account %s from %s", username, key)
    return record


def sso_session_claims(profile: SsoProfile, account: dict[str, Any]) -> dict[str, Any]:
    """Claims to bake into the normal DeepTutor session token.

    ``create_token`` already embeds ``tenant`` from the request context; SSO
    providers may assert groups that map to tenant membership, which the caller
    can translate before this helper is invoked.
    """
    return {
        "username": str(account.get("username") or ""),
        "role": str(account.get("role") or "user"),
        "user_id": str(account.get("id") or ""),
    }


