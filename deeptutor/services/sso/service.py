def parse_saml_response(raw_saml: str) -> SamlResponseEnvelope:
    """Parse a base64-encoded SAML Response into its parts without verification.

    Use :func:`verify_saml_response` for the security-sensitive path; this
    only extracts the fields needed for verification/error messages.
    """
    from .saml import parse_saml_response as _parse

    return _parse(raw_saml)


async def verify_saml_response(
    provider: SamlProviderConfig,
    raw_saml: str,
    *,
    expected_relay_state: str,
    relay_state: str | None = None,
) -> SsoProfile:
    """Verify a SAML Response (HTTP-POST binding) and return its profile.

    The signature is checked against the IdP certificate, the Audience
    restriction must name our SP, and the RelayState must match what the SP
    issued.
    """
    if not hmac.compare_digest(relay_state or "", expected_relay_state or ""):
        raise SsoStateError("SAML RelayState mismatch")
    from .saml import verify_saml_response as _verify

    return _verify(provider, raw_saml)


